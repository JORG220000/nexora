export const properties: Property[] = seeds.map(
  ([name, ci, type, price, area, beds, baths, en, ru, fe, fr], i) => {
    const c = cities[ci],
      n = String(i + 1).padStart(2, "0");
    return {
      id: `demo-${n}`,
      slug: name
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[^a-z0-9]+/g, "-"),
      name,
      city: c.name,
      country: c.country,
      district: c.district,
      lat: c.lat + (i % 3) * 0.007,
      lng: c.lng + (i % 3) * 0.005,
      type,
      deal: [3, 6, 10].includes(i) ? "rent" : "buy",
      price,
      period: i === 6 ? "week" : "month",
      area,
      beds,
      baths,
      description: { en, ru },
      features: { en: fe, ru: fr },
      amenities:
        type === "apartment"
          ? ["terrace", "gym", "parking", "concierge"]
          : ["pool", "terrace", "garden", "parking", i % 2 ? "spa" : "cinema"],
      photos: [0, 1, 2, 3].map((frame) => ({
        src: `/media/property-${n}.webp`,
        frame,
      })),
      added: `2026-${String(10 - (i % 5)).padStart(2, "0")}-${String(10 + i).padStart(2, "0")}`,
      popularity: 100 - i * 4,
    };
  },
);
